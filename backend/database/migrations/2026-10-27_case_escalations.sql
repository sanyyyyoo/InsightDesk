-- Run once in the Supabase SQL editor (TEST project first, then live).
-- Records every escalation an operator approves; the backend works without it but then keeps no record.
create table if not exists case_escalations (
    escalation_id  bigint generated by default as identity primary key,
    case_id        bigint not null references cases(case_id) on delete cascade,
    department     text not null,
    receiver       text not null,
    rca_id         bigint references case_rca(rca_id) on delete set null,
    escalated_at   timestamptz not null default now()
);
create index if not exists case_escalations_case_idx on case_escalations (case_id, escalated_at desc);
