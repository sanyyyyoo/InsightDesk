-- InsightDesk database schema (Supabase / PostgreSQL)
-- Derived from the queries in backend/database/supabase.py.
-- Run once in a NEW Supabase project: Dashboard -> SQL Editor -> paste -> Run.

-- ---------------------------------------------------------------
-- Topics (discovered by BERTopic clustering)
-- ---------------------------------------------------------------
create table if not exists topics (
    topic_id            bigint generated by default as identity primary key,
    topic_name          text not null,
    topic_slug          text not null unique,
    department          text,
    department_override text,
    description         text,
    clustering_run_id   integer,
    created_at          timestamptz not null default now(),
    updated_at          timestamptz
);

-- ---------------------------------------------------------------
-- Cases (one real problem; groups duplicate complaints)
-- ---------------------------------------------------------------
create table if not exists cases (
    case_id             bigint generated by default as identity primary key,
    representative_text text not null,
    report_count        integer not null default 1,
    user_ids            text[] not null default '{}',
    topic_id            bigint references topics(topic_id) on delete set null,
    sentiment           text,
    confidence_score    double precision,
    sentiment_model     text,
    emotion             text,
    emotion_confidence  double precision,
    spike_status        boolean not null default false,
    is_vague            boolean not null default false,   -- R1: judge found no concrete symptom
    spike_score         double precision,
    spike_detected_at   timestamptz,
    created_at          timestamptz not null default now(),
    last_reported_at    timestamptz not null default now()
);

-- ---------------------------------------------------------------
-- Complaints (one message from one customer)
-- ---------------------------------------------------------------
create table if not exists complaints (
    complaint_id    bigint generated by default as identity primary key,
    complaint_text  text not null,
    cleaned_text    text,
    user_id         text not null,
    rating          integer,
    source          text,
    product         text,
    company_size    text,
    is_synthetic    boolean not null default false,
    case_id         bigint references cases(case_id) on delete set null,
    is_duplicate    boolean not null default false,
    created_at      timestamptz not null default now()
);
create index if not exists complaints_case_idx       on complaints (case_id);
create index if not exists complaints_user_case_idx  on complaints (user_id, case_id, created_at);
create index if not exists complaints_created_idx    on complaints (created_at);

-- ---------------------------------------------------------------
-- Complaint windows (6-hour counts per case, used by spike detection)
-- ---------------------------------------------------------------
create table if not exists complaint_windows (
    window_id     bigint generated by default as identity primary key,
    case_id       bigint not null references cases(case_id) on delete cascade,
    window_start  timestamptz not null,
    window_end    timestamptz not null,
    complaint_ct  integer not null default 0,
    unique (case_id, window_start)
);

-- ---------------------------------------------------------------
-- Case history (report_count snapshots; written on every new report)
-- ---------------------------------------------------------------
create table if not exists case_history (
    history_id    bigint generated by default as identity primary key,
    case_id       bigint not null references cases(case_id) on delete cascade,
    report_count  integer not null,
    created_at    timestamptz not null default now()
);

-- ---------------------------------------------------------------
-- Root cause analyses (LLM output, cached per case)
-- ---------------------------------------------------------------
create table if not exists case_rca (
    rca_id              bigint generated by default as identity primary key,
    case_id             bigint not null references cases(case_id) on delete cascade,
    probable_cause      text not null,
    affected_segment    text,
    recommended_action  text,
    severity            text,
    confidence          double precision,
    source_evidence     jsonb not null default '[]'::jsonb,
    generated_at        timestamptz not null default now(),
    model_used          text
);
create index if not exists case_rca_case_idx on case_rca (case_id, generated_at desc);

-- ---------------------------------------------------------------
-- Clustering metadata (drives the re-clustering decision)
-- ---------------------------------------------------------------
create table if not exists clustering_metadata (
    metadata_id         bigint generated by default as identity primary key,
    clustering_version  integer not null default 0,
    last_case_count     integer not null default 0,
    total_topics        integer not null default 0,
    outlier_rate        double precision not null default 0,
    last_clustered_at   timestamptz
);

-- ---------------------------------------------------------------
-- Sentiment model benchmarks
-- ---------------------------------------------------------------
create table if not exists model_benchmarks (
    benchmark_id          bigint generated by default as identity primary key,
    model_name            text not null,
    complaints_processed  integer,
    average_latency_ms    double precision,
    throughput            double precision,
    memory_mb             double precision,
    created_at            timestamptz not null default now()
);
